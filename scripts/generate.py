"""Generate ``src/pyogmios/_generated`` from the pinned Ogmios schema.

1. ``build_schema.py`` combines ``ogmios.json`` and ``cardano.json`` into one schema with named definitions.
2. datamodel-code-generator turns it into Pydantic models (options in ``[tool.datamodel-codegen]``).
3. This script writes the method table, ``methods.py``, from ``methods.json``.

Usage: python scripts/generate.py [ogmios version]   (default: the version in schemas/VERSION)
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src" / "pyogmios" / "_generated"

HEADER = '''"""{what} for Ogmios v{version}.

Generated by scripts/generate.py from schemas/v{version}. Do not edit by hand: run `just regen-models`.
"""'''


def run(*args: str) -> None:
    subprocess.run(args, check=True, cwd=ROOT)


def write_methods(methods: dict[str, dict], version: str) -> str:
    lines = [
        HEADER.format(what="The JSON-RPC methods", version=version),
        "",
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass",
        "from typing import Any",
        "",
        "from . import models",
        "",
        f'OGMIOS_VERSION = "{version}"',
        "",
        "",
        "@dataclass(frozen=True, slots=True)",
        "class MethodSpec:",
        '    """How to call one Ogmios method and read its answer."""',
        "",
        "    name: str",
        '    """The JSON-RPC method name, for example ``queryLedgerState/epoch``."""',
        "    schema_name: str",
        '    """The request\'s name in ogmios.json, for example ``QueryLedgerStateEpoch``."""',
        "    params: Any",
        '    """The params model, or ``None`` when the method takes no params."""',
        "    params_required: bool",
        '    """Whether the schema requires params."""',
        "    result: Any",
        '    """The type of a successful ``result``."""',
        "    errors: tuple[Any, ...]",
        '    """The method-specific ``error`` types it can return."""',
        "",
        "",
        "METHODS: dict[str, MethodSpec] = {",
    ]
    for name, spec in methods.items():
        params = f"models.{spec['params']}" if spec["params"] else "None"
        errors = "".join(f"models.{error}, " for error in spec["errors"])
        lines += [
            f'    "{name}": MethodSpec(',
            f'        name="{name}",',
            f'        schema_name="{spec["request"]}",',
            f"        params={params},",
            f"        params_required={spec['params_required']},",
            f"        result=models.{spec['result']},",
            f"        errors=({errors}),",
            "    ),",
        ]
    lines += ["}", ""]
    return "\n".join(lines)


def add_all(path: Path) -> None:
    """List every generated type in ``__all__``, so ``pyogmios.types`` can re-export exactly those."""
    source = path.read_text()
    names = sorted(set(re.findall(r"^(?:class (\w+)\(|(\w+) = TypeAliasType\()", source, re.M)))
    exported = sorted(a or b for a, b in names)
    listing = "".join(f'    "{name}",\n' for name in exported)
    path.write_text(f"{source.rstrip()}\n\n\n__all__ = [\n{listing}]\n")


def main() -> None:
    version = (
        sys.argv[1] if len(sys.argv) > 1 else (ROOT / "schemas" / "VERSION").read_text().strip()
    )
    schemas = ROOT / "schemas" / f"v{version}"
    OUTPUT.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory() as tmp:
        run(sys.executable, "scripts/build_schema.py", str(schemas), tmp)
        header = Path(tmp) / "header.txt"
        header.write_text(
            HEADER.format(what="Pydantic models of every Ogmios and Cardano type", version=version)
        )
        run(
            "datamodel-codegen",
            "--input", str(Path(tmp) / "combined.json"),
            "--output", str(OUTPUT / "models.py"),
            "--custom-file-header-path", str(header),
        )  # fmt: skip
        methods = json.loads((Path(tmp) / "methods.json").read_text())

    add_all(OUTPUT / "models.py")
    (OUTPUT / "methods.py").write_text(write_methods(methods, version))
    (OUTPUT / "__init__.py").write_text(
        HEADER.format(what="Generated code", version=version) + "\n"
    )
    run("ruff", "format", "--quiet", str(OUTPUT))
    run("ruff", "check", "--quiet", "--fix", str(OUTPUT))
    print(f"Generated {OUTPUT.relative_to(ROOT)} for Ogmios v{version} ({len(methods)} methods)")


if __name__ == "__main__":
    main()
